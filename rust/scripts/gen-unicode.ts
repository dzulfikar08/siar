// Regenerates rust/src/unicode_tables.rs: the code points JavaScript matches with
// /[\p{L}\p{N}_]/u (TAG_CHAR) and /\p{L}/u (LETTER).
//   bun rust/scripts/gen-unicode.ts
const ranges = (re: RegExp) => {
  const r: [number, number][] = [];
  let start = -1;
  for (let cp = 0; cp <= 0x10ffff; cp++) {
    const ok = !(cp >= 0xd800 && cp <= 0xdfff) && re.test(String.fromCodePoint(cp));
    if (ok && start < 0) start = cp;
    if (!ok && start >= 0) {
      r.push([start, cp - 1]);
      start = -1;
    }
  }
  if (start >= 0) r.push([start, 0x10ffff]);
  return r;
};
const table = (name: string, r: [number, number][]) => {
  let s = `#[rustfmt::skip]\npub const ${name}: &[(u32, u32)] = &[\n`;
  for (let i = 0; i < r.length; i += 8) s += `    ${r.slice(i, i + 8).map(([a, b]) => `(0x${a.toString(16)}, 0x${b.toString(16)})`).join(", ")},\n`;
  return `${s}];\n`;
};
const tag = ranges(/[\p{L}\p{N}_]/u);
const letter = ranges(/\p{L}/u);
let out = `//! \`[\\p{L}\\p{N}_]\` and \`\\p{L}\` as JavaScript (Bun ${Bun.version}, u flag) sees them, generated by rust/scripts/gen-unicode.ts.\n//! Rust has no general-category API in std, and char::is_alphanumeric also accepts marks.\n\n`;
out += table("TAG_CHAR", tag) + "\n" + table("LETTER", letter);
await Bun.write(`${import.meta.dir}/../src/unicode_tables.rs`, out);
console.log(`${tag.length} tag ranges, ${letter.length} letter ranges`);
